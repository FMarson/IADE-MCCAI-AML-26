function parseSMSData(rows) {
  let data = [];

  for (let row of rows) {
    let separatorIndex = row.indexOf("\t");

    if (separatorIndex === -1) {
      continue;
    }

    let label = row.substring(
      0,
      separatorIndex
    ).trim();

    let message = row.substring(
      separatorIndex + 1
    ).trim();

    if (
      (label === "ham" || label === "spam") &&
      message.length > 0
    ) {
      data.push({
        label: label,
        message: message
      });
    }
  }

  return data;
}


function splitDataset(data, testRatio) {
  let shuffled = shuffle(
    data,
    true
  );

  let testSize = floor(
    shuffled.length * testRatio
  );

  return {
    test: shuffled.slice(0, testSize),
    train: shuffled.slice(testSize)
  };
}


function tokenize(text) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .split(/\s+/)
    .filter(word => word.length > 0);
}


function buildVocabulary(data) {
  let vocabularySet = new Set();

  for (let item of data) {
    let words = tokenize(item.message);

    for (let word of words) {
      vocabularySet.add(word);
    }
  }

  return Array.from(vocabularySet);
}


function trainNaiveBayes(data, modelVocabulary) {
  naiveBayesModel = {
    classDocumentCounts: {
      ham: 0,
      spam: 0
    },

    classWordCounts: {
      ham: {},
      spam: {}
    },

    classTotalWords: {
      ham: 0,
      spam: 0
    },

    totalDocuments: data.length
  };

  for (let item of data) {
    let label = item.label;
    let words = tokenize(item.message);

    naiveBayesModel.classDocumentCounts[label]++;

    for (let word of words) {
      if (
        naiveBayesModel.classWordCounts[label][word]
        === undefined
      ) {
        naiveBayesModel.classWordCounts[label][word] = 0;
      }

      naiveBayesModel.classWordCounts[label][word]++;
      naiveBayesModel.classTotalWords[label]++;
    }
  }

  console.log(
    "Naive Bayes training completed."
  );
}


function predictNaiveBayes(message) {
  let words = tokenize(message);
  let vocabularySize = vocabulary.length;

  let scores = {};

  for (let label of ["ham", "spam"]) {
    let documentCount =
      naiveBayesModel.classDocumentCounts[label];

    let prior =
      documentCount /
      naiveBayesModel.totalDocuments;

    let logProbability = Math.log(prior);

    for (let word of words) {
      let wordCount =
        naiveBayesModel.classWordCounts[label][word]
        || 0;

      let probability =
        (wordCount + 1) /
        (
          naiveBayesModel.classTotalWords[label]
          + vocabularySize
        );

      logProbability += Math.log(probability);
    }

    scores[label] = logProbability;
  }

  return scores.spam > scores.ham
    ? "spam"
    : "ham";
}


function trainKNN(data, modelVocabulary) {
  knnModel.vocabulary = modelVocabulary;
  knnModel.examples = [];

  for (let item of data) {
    let vector = messageToVector(
      item.message,
      modelVocabulary
    );

    knnModel.examples.push({
      vector: vector,
      label: item.label
    });
  }

  console.log(
    "kNN training completed."
  );
}


function messageToVector(message, modelVocabulary) {
  let words = tokenize(message);
  let wordCounts = {};

  for (let word of words) {
    wordCounts[word] =
      (wordCounts[word] || 0) + 1;
  }

  let vector = [];

  for (let word of modelVocabulary) {
    vector.push(
      wordCounts[word] || 0
    );
  }

  return vector;
}


function cosineSimilarity(vectorA, vectorB) {
  let dotProduct = 0;
  let magnitudeA = 0;
  let magnitudeB = 0;

  for (let i = 0; i < vectorA.length; i++) {
    dotProduct +=
      vectorA[i] * vectorB[i];

    magnitudeA +=
      vectorA[i] * vectorA[i];

    magnitudeB +=
      vectorB[i] * vectorB[i];
  }

  if (
    magnitudeA === 0 ||
    magnitudeB === 0
  ) {
    return 0;
  }

  return dotProduct /
    (
      Math.sqrt(magnitudeA) *
      Math.sqrt(magnitudeB)
    );
}


function predictKNN(message, k = 5) {
  let inputVector = messageToVector(
    message,
    knnModel.vocabulary
  );

  let similarities = [];

  for (let example of knnModel.examples) {
    let similarity = cosineSimilarity(
      inputVector,
      example.vector
    );

    similarities.push({
      similarity: similarity,
      label: example.label
    });
  }

  similarities.sort(
    (a, b) => b.similarity - a.similarity
  );

  let nearest = similarities.slice(0, k);

  let hamCount = 0;
  let spamCount = 0;

  for (let item of nearest) {
    if (item.label === "spam") {
      spamCount++;
    } else {
      hamCount++;
    }
  }

  return spamCount > hamCount
    ? "spam"
    : "ham";
}


function calculateConfusionMatrix(
  actual,
  predicted
) {
  let tp = 0;
  let tn = 0;
  let fp = 0;
  let fn = 0;

  for (let i = 0; i < actual.length; i++) {
    if (
      actual[i] === "spam" &&
      predicted[i] === "spam"
    ) {
      tp++;
    } else if (
      actual[i] === "ham" &&
      predicted[i] === "ham"
    ) {
      tn++;
    } else if (
      actual[i] === "ham" &&
      predicted[i] === "spam"
    ) {
      fp++;
    } else if (
      actual[i] === "spam" &&
      predicted[i] === "ham"
    ) {
      fn++;
    }
  }

  return {
    tp: tp,
    tn: tn,
    fp: fp,
    fn: fn
  };
}


function safeDivide(numerator, denominator) {
  if (denominator === 0) {
    return 0;
  }

  return numerator / denominator;
}


function calculateMetrics(matrix) {
  let tp = matrix.tp;
  let tn = matrix.tn;
  let fp = matrix.fp;
  let fn = matrix.fn;

  let accuracy = safeDivide(
    tp + tn,
    tp + tn + fp + fn
  );

  let precision = safeDivide(
    tp,
    tp + fp
  );

  let recall = safeDivide(
    tp,
    tp + fn
  );

  let specificity = safeDivide(
    tn,
    tn + fp
  );

  let f1 = safeDivide(
    2 * precision * recall,
    precision + recall
  );

  return {
    accuracy: accuracy,
    precision: precision,
    recall: recall,
    specificity: specificity,
    f1: f1
  };
}


function evaluateModels() {
  if (testMessages.length === 0) {
    statusMessage = "No test messages available.";
    return;
  }

  console.log("Evaluating Naive Bayes...");

  let actual = [];
  let naiveBayesPredictions = [];

  for (let item of testMessages) {
    actual.push(item.label);

    naiveBayesPredictions.push(
      predictNaiveBayes(item.message)
    );
  }

  let naiveBayesMatrix =
    calculateConfusionMatrix(
      actual,
      naiveBayesPredictions
    );

  nbMetrics = calculateMetrics(
    naiveBayesMatrix
  );

  console.log(
    "Naive Bayes confusion matrix:",
    naiveBayesMatrix
  );

  console.log(
    "Naive Bayes metrics:",
    nbMetrics
  );

  console.log("Evaluating kNN...");

  let knnPredictions = [];

  for (let item of testMessages) {
    knnPredictions.push(
      predictKNN(item.message, 5)
    );
  }

  let knnMatrix =
    calculateConfusionMatrix(
      actual,
      knnPredictions
    );

  knnMetrics = calculateMetrics(
    knnMatrix
  );

  console.log(
    "kNN confusion matrix:",
    knnMatrix
  );

  console.log(
    "kNN metrics:",
    knnMetrics
  );

  statusMessage =
    "Evaluation completed.";

  redraw();
}


